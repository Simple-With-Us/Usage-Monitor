#!/usr/bin/env node
// Refreshes the bundled LiteLLM model-pricing snapshot consumed by
// src/lib/pricing/model-pricing.ts.
//
// Why a bundled snapshot instead of a runtime fetch (the ccusage pattern:
// they pin BerriAI/litellm as a locked flake input and refresh it with an
// explicit `just update-litellm-pricing` step):
//   - Ingest/read paths never depend on GitHub availability or latency.
//   - Pricing changes are reviewable diffs in this repo, not silent drift.
//   - The snapshot records its provenance (source URL + fetch time) so every
//     derived cost can be attributed to an exact pricing revision.
//
// Usage:  node scripts/update-model-pricing.mjs
// Env:    LITELLM_PRICING_URL  (override the upstream catalog URL, e.g. to
//         pin a specific commit:
//         https://raw.githubusercontent.com/BerriAI/litellm/<sha>/model_prices_and_context_window.json)

import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_URL =
  "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json";
const OUT_PATH = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "lib",
  "pricing",
  "model-pricing.snapshot.json"
);

// Only fields the pricing module reads. Anything else (context windows,
// capability flags, search-context pricing, ...) stays upstream; keeping the
// snapshot small keeps the serverless bundle small and the diff reviewable.
const KEPT_FIELDS = [
  "input_cost_per_token",
  "output_cost_per_token",
  "cache_read_input_token_cost",
  "cache_creation_input_token_cost",
  "cache_creation_input_token_cost_above_1hr",
  "input_cost_per_token_above_200k_tokens",
  "output_cost_per_token_above_200k_tokens",
  "cache_read_input_token_cost_above_200k_tokens",
  "cache_creation_input_token_cost_above_200k_tokens",
  "litellm_provider",
  "mode",
  "max_input_tokens",
];

// Canary models that MUST exist in the upstream catalog; if any is missing
// the upstream format almost certainly changed and a stale/broken snapshot
// would silently zero-out derived costs.
const CANARY_KEYS = ["claude-sonnet-4-5", "gpt-4o"];

const url = process.env.LITELLM_PRICING_URL ?? DEFAULT_URL;

const res = await fetch(url, { headers: { "user-agent": "api-usage-monitor pricing-refresh" } });
if (!res.ok) {
  console.error(`fetch failed: ${res.status} ${res.statusText} (${url})`);
  process.exit(1);
}
const raw = await res.text();
const upstreamSha256 = createHash("sha256").update(raw).digest("hex");

/** @type {Record<string, Record<string, unknown>>} */
const catalog = JSON.parse(raw);

const pricing = {};
let skippedNoCost = 0;
for (const [key, value] of Object.entries(catalog)) {
  if (key === "sample_spec" || !value || typeof value !== "object") continue;
  const entry = {};
  let hasCost = false;
  for (const field of KEPT_FIELDS) {
    const fieldValue = value[field];
    if (typeof fieldValue === "number" && Number.isFinite(fieldValue)) {
      entry[field] = fieldValue;
      if (field.endsWith("cost_per_token") || field.includes("token_cost")) hasCost = true;
    } else if (field === "litellm_provider" || field === "mode") {
      if (typeof fieldValue === "string") entry[field] = fieldValue;
    }
  }
  if (!hasCost) {
    skippedNoCost += 1;
    continue;
  }
  pricing[key] = entry;
}

for (const canary of CANARY_KEYS) {
  if (!pricing[canary]) {
    console.error(
      `upstream catalog no longer contains expected model "${canary}" — refusing to write a suspect snapshot`
    );
    process.exit(1);
  }
}

const snapshot = {
  meta: {
    source: url,
    fetchedAt: new Date().toISOString(),
    upstreamSha256,
    modelCount: Object.keys(pricing).length,
    note: "Generated by scripts/update-model-pricing.mjs from the LiteLLM model_prices_and_context_window.json catalog. Do not hand-edit; re-run the script.",
  },
  pricing,
};

await writeFile(OUT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`, "utf8");
console.log(
  `wrote ${Object.keys(pricing).length} priced models (skipped ${skippedNoCost} unpriced entries) -> ${path.relative(process.cwd(), OUT_PATH)}`
);
console.log(`upstream sha256: ${upstreamSha256}`);
